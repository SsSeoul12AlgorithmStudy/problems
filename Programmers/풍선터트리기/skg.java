/*

모든 경우에 대해서 생각?
아니면 각 풍선별로 시뮬레이션 해야 하나?

일단 브루트포스로 풀어볼까?
근데 백만개까지니까 너무 경우의 수가 많을 것 같은데..
단순히만 생각해도 첫 인접 두개 고르는 게 백만 -> 그 다음 999,999 -> ...
= 1,000,000 * 999,999 * ... * 1 = O(N!) 안 될 것 같다..

특정 풍선 k를 기준으로
1. 만약 오른쪽에 풍선이 없다 = 무조건 가능!
    왜냐면 오른쪽에 있는 풍선끼리만 치고박고 하다가 최종적으로 남은 풍선이 k보다 크든 작든 터뜨릴 수 있으므로
2. 만약 왼쪽에 풍선이 없다 = 같은 이유로 무조건 가능!
3. 중간에 껴있다면?

왼쪽 오른쪽에서부터 DP를 하면 되려나?
L[i][j] : 0번 풍선 ~ i번 풍선
    j = 0 -> 번호가 더 작은 풍선을 터뜨리지 않았을 때 최종적으로 남는 풍선 = 0~i까지 중 최솟값
    j = 1 -> 번호가 더 작은 풍선을 터뜨렸을 때 최종적으로 남는 풍선의 최댓값

L[i][1] = Math.max(Math.max(L[i-1][0], a[i]), Math.min(L[i-1][1], a[i]));
L[i][0] = Math.min(Math.min(L[i-1][0]));

    -16 27  65  -2  58  -92 -71 -68 -61 -33
0   -16 -16 -16 -16 -16 -92 -92 -92 -92 -92
1   x   27  65  -2  58  -16 -71 -68 -61 -33
더 작은 풍선 터뜨리는 건 한번만(더 큰 풍선 생존)

오른쪽에서부터 똑같이 진행
    -33 -61 -68 -71 -92 58  -2  65  27  -16
0   -33 -61 -68 -71 -92 -92 -92 -92 -92 -92
1   x   -33 -61 -68 -71 58  -2  65  27  -16

가운데에 있는 i번째 수에 대해서
L[i-1][0]   R[i+1][0] 
L[i-1][1]   R[i+1][1]
1. L[i-1][0]과 R[i+1][0] 중 하나 이상 a[i]보다 큰 경우
2. L[i-1][1]과 R[i+1][0] 모두 a[i]보다 큰 경우
3. L[i-1][0]과 R[i+1][1] 모두 a[i]보다 큰 경우

너무 어려운데..?

핵심 아이디어는 현재 풍선 k 기준으로
1. 왼쪽 풍선 무리와 오른쪽 풍선 무리 각각에서 찬스를 썼을 때/안 썼을 때 값들을 구해서
2. 풍선 k가 찬스를 써서/안써서 살아남을 수 있는지 확인

*/

class Solution {
    int[][] L;
    int[][] R;
    
    public int solution(int[] a) {
        int answer = 0;
        int N = a.length;
        
        L = new int[N][2];
        R = new int[N][2];
        
        L[0][0] = a[0];
        L[0][1] = a[0];
        
        R[N-1][0] = a[N-1];
        R[N-1][1] = a[N-1];
        
        for (int i = 1; i < N; i++) {
            L[i][0] = Math.min(L[i-1][0], a[i]);
            L[i][1] = Math.max(Math.min(L[i-1][1], a[i]), Math.max(L[i-1][0], a[i]));
        }
        
        for (int i = N-2; i >= 0; i--) {
            R[i][0] = Math.min(R[i+1][0], a[i]);
            R[i][1] = Math.max(Math.min(R[i+1][1], a[i]), Math.max(R[i+1][0], a[i]));
        }
        
        for (int i = 0; i < N; i++) {
            if (i == 0 || i == N-1) {
                answer++;
                continue;
            }
            if (!(L[i-1][0] < a[i] && R[i+1][0] < a[i]))    answer++;
            else if (L[i-1][0] > a[i] && R[i-1][1] > a[i])  answer++;
            else if (L[i-1][1] > a[i] && R[i-1][0] > a[i])  answer++;
        }
        
        return answer;
    }
}

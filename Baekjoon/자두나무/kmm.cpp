	//근데 그걸 판단할려면 앞으로 얼마나 많이 놓여져있는지를 알아야 하잖아
	//1번으로 갔을때의 최대값과 2번으로 갔을때의 최대값인가?
	//최대 비교하는게, 현재 1로 옮겼을 때 최대, 현재 2로 옮겼을 때 최대?

	//i는 시간, j는 스왑하는 횟수? (j는 30이 풀)
	//짝수번 이동이면 1번 나무, 홀수면 2번 나무
	//loc = (j % 2) ? 1 : 2;
	//현재 자두 = max(이전 자두에서 움직이지 않았을때, 이전 자두에서 움직였을 때) + 현재 위치
	//dp[i][j] = max(dp[i-1][j], dp[i-1][j-1]) + (loc == fall[i])

	//소분하는 기준이 좀 어렵네 많이 풀어봐야 알 듯

int t, w;
vector<int> fall;
vector<vector<int>> dp;
int main() {
	cin >> t >> w;

	dp.assign(t + 1, vector<int>(w + 1, 0));
	fall.resize(t + 1);
	for (int i = 1; i <= t; i++) {
		cin >> fall[i];
	}

	for (int i = 1; i <= t; i++) {
		for (int j = 0; j <= w; j++) {
			//짝수면 1번나무, 홀수면 2번나무
			int loc = (j % 2 == 0) ? 1 : 2;
			int isCatch = (loc == fall[i]);
			//움직이지 않고, 지금 나무가 뭔지만 파악
			if (j == 0) dp[i][j] = dp[i - 1][j] + isCatch;
			else dp[i][j] = max(dp[i - 1][j], dp[i - 1][j - 1]) + isCatch;
		}
	}

	int ans = 0;
	//가장 끝초에서 몇번 움직였을 때 최대값인지
	for (int j = 0; j <= w; j++) {
		ans = max(ans, dp[t][j]);
	}

	cout << ans << "\n";
}

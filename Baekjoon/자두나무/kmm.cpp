//어느 나무에서 떨어질지에 대한 정보가 주어지면, 자두가 받을 수 있는 자두의 개수
//자두는 1번 자두나무 아래 위치

	//이걸 dp로 푼다고?
	//흠 어떻게 풀어야하지
	//받을 수 있냐? 없냐?
	//dp[0] = 0
	//아니면 1을 선택했을때의 경우 dp와 2를 선택했을때의 경우 dp일려나
	//흠 혹은 최대 30번만 이동 가능하다고 했는데, 이동을 했을때와 안했을때?
	//근데 사용하는게 한 번만 있는것도 아니고 30번인데
	//문제를 작게 쪼개보자
